def build_trial_balance_workbook(
    meta: WorkbookMeta,
    tb_rows: Sequence[TrialBalanceRow],
    validation_items: list[dict] | None = None,
    workflow_tasks: list[dict] | None = None,
    workflow_signoffs: list[dict] | None = None,
    issues: list[dict] | None = None,
) -> Workbook:
    wb = Workbook()
    _add_cover_sheet(wb, meta)
    _add_metadata_sheet(wb, meta)
    _add_tb_sheet(wb, tb_rows, "Trial Balance")
    if validation_items:
        _add_validation_sheet(wb, validation_items)
    if workflow_tasks is not None or workflow_signoffs is not None:
        _add_workflow_sheet(wb, workflow_tasks or [], workflow_signoffs or [])
    if issues:
        _add_issues_sheet(wb, issues)
    return wb


def build_fs_workbook(
    meta: WorkbookMeta,
    tb_rows: Sequence[TrialBalanceRow],
    fs_lines: Sequence[FsLineBalance],
    validation_items: list[dict] | None = None,
    workflow_tasks: list[dict] | None = None,
    workflow_signoffs: list[dict] | None = None,
    issues: list[dict] | None = None,
) -> Workbook:
    wb = Workbook()
    _add_cover_sheet(wb, meta)
    _add_metadata_sheet(wb, meta)
    _add_tb_sheet(wb, tb_rows, "Trial Balance")

    bs_lines = [l for l in fs_lines if l.statement == "BS"]
    is_lines = [l for l in fs_lines if l.statement == "IS"]
    cf_lines = [l for l in fs_lines if l.statement == "CF"]
    if bs_lines:
        _add_fs_sheet(wb, bs_lines, sheet_title="Balance Sheet")
    if is_lines:
        _add_fs_sheet(wb, is_lines, sheet_title="Income Statement")
    if cf_lines:
        _add_fs_sheet(wb, cf_lines, sheet_title="Cash Flow")

    if validation_items:
        _add_validation_sheet(wb, validation_items)
    if workflow_tasks is not None or workflow_signoffs is not None:
        _add_workflow_sheet(wb, workflow_tasks or [], workflow_signoffs or [])
    if issues:
        _add_issues_sheet(wb, issues)
    return wb


