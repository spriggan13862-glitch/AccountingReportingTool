_HEADER_FILL = PatternFill("solid", fgColor="1F4E79")
_HEADER_FONT = Font(bold=True, color="FFFFFF", size=11)
_SUBHEADER_FILL = PatternFill("solid", fgColor="D6E4F0")
_SUBHEADER_FONT = Font(bold=True, size=10)
_BOLD_FONT = Font(bold=True, size=10)
_NORMAL_FONT = Font(size=10)
_TOTAL_FONT = Font(bold=True, size=10, underline="singleAccounting")

_NUMBER_FMT = '#,##0.00'
_DATE_FMT = 'YYYY-MM-DD'

_FIXED_EPOCH = datetime.datetime(2000, 1, 1, 0, 0, 0)


# ---------------------------------------------------------------------------
# Metadata carrier
# ---------------------------------------------------------------------------

@dataclass
class WorkbookMeta:
    report_type: str
    entity_name: str = ""
    organization_name: str = ""
    as_of_date: datetime.date | None = None
    scenario_labels: list[str] = field(default_factory=list)
    period_name: str = ""
    generated_by: str = ""
    generation_time: datetime.datetime | None = None
    extra: dict[str, Any] = field(default_factory=dict)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _write_header_row(ws, values: list[str], row: int = 1) -> None:
    for col, val in enumerate(values, start=1):
        cell = ws.cell(row=row, column=col, value=val)
        cell.font = _HEADER_FONT
        cell.fill = _HEADER_FILL
        cell.alignment = Alignment(horizontal="center")


def _write_subheader_row(ws, values: list[str], row: int) -> None:
    for col, val in enumerate(values, start=1):
        cell = ws.cell(row=row, column=col, value=val)
        cell.font = _SUBHEADER_FONT
        cell.fill = _SUBHEADER_FILL


def _write_label_value(ws, row: int, label: str, value: Any) -> None:
    ws.cell(row=row, column=1, value=label).font = _BOLD_FONT
    ws.cell(row=row, column=2, value=value).font = _NORMAL_FONT


def _auto_width(ws, min_width: int = 10, max_width: int = 50) -> None:
    for col in ws.columns:
        best = min_width
        for cell in col:
            if cell.value is not None:
                best = min(max(best, len(str(cell.value)) + 2), max_width)
        ws.column_dimensions[get_column_letter(col[0].column)].width = best


def _set_number_col(ws, col: int, start_row: int, end_row: int) -> None:
    for row in range(start_row, end_row + 1):
        ws.cell(row=row, column=col).number_format = _NUMBER_FMT


