"""
Report-run orchestration service.

Responsibilities
----------------
- Create and persist ReportRun records
- Dispatch execution to the export service
- Store generated bytes via StorageBackend
- Create a Document record and link it to the run on completion
- Populate validation_summary_json and workflow_summary_json
"""

from __future__ import annotations

import datetime
import json
import uuid
from typing import TYPE_CHECKING

from sqlalchemy.orm import Session

from app.models.report_run import (
    OUTPUT_FORMATS,
    REPORT_TYPE_DOC_TYPE,
    REPORT_TYPES,
    ReportRun,
)

if TYPE_CHECKING:
    from app.models.user import User
    from app.services.storage_service import StorageBackend


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------

class ReportRunNotFoundError(LookupError):
    pass


class ReportRunStateError(ValueError):
    pass


class ReportValidationError(ValueError):
    pass


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _get_scenario_ids(run: ReportRun) -> list[int]:
    if not run.scenario_ids_json:
        return []
    return json.loads(run.scenario_ids_json)


def _build_validation_summary(result) -> dict:
    """Convert a ValidationResult to a JSON-serialisable dict."""
    if result is None:
        return {"success": True, "errors": [], "warnings": [], "info": []}
    return {
        "success": result.success,
        "errors": [i.to_dict() for i in result.errors],
        "warnings": [i.to_dict() for i in result.warnings],
        "info": [i.to_dict() for i in result.infos],
    }


def _collect_workflow_summary(
    db: Session,
    run: ReportRun,
) -> dict:
    """Pull open tasks and signoffs related to the entity/period for the run."""
    from app.services.workflow_service import list_issues, list_signoffs, list_tasks

    tasks_data: list[dict] = []
    signoffs_data: list[dict] = []
    issues_data: list[dict] = []

    if run.organization_id:
        raw_tasks = list_tasks(db, run.organization_id)
        tasks_data = [
            {
                "id": t.id,
                "title": t.title,
                "task_type": t.task_type,
                "status": t.status,
                "priority": t.priority,
                "assigned_to_user_id": t.assigned_to_user_id,
                "due_date": str(t.due_date) if t.due_date else None,
            }
            for t in raw_tasks
        ]
        raw_issues = list_issues(db, run.organization_id)
        issues_data = [
            {
                "id": i.id,
                "issue_code": i.issue_code,
                "severity": i.severity,
                "title": i.title,
                "status": i.status,
                "related_object_type": i.related_object_type,
                "related_object_id": i.related_object_id,
                "opened_at": str(i.opened_at) if i.opened_at else None,
                "resolved_at": str(i.resolved_at) if i.resolved_at else None,
                "resolution_notes": i.resolution_notes,
            }
            for i in raw_issues
        ]

    if run.accounting_period_id:
        raw_signoffs = list_signoffs(db, "accounting_period", run.accounting_period_id)
        signoffs_data = [
            {
                "id": s.id,
                "object_type": s.object_type,
                "object_id": s.object_id,
                "reviewer_user_id": s.reviewer_user_id,
                "signoff_status": s.signoff_status,
                "signed_at": str(s.signed_at) if s.signed_at else None,
                "notes": s.notes,
            }
            for s in raw_signoffs
        ]

    return {
        "tasks": tasks_data,
        "signoffs": signoffs_data,
        "issues": issues_data,
    }


def _dispatch_report(db: Session, run: ReportRun) -> bytes:
    """Build the workbook bytes for a report run."""
    from app.models.entity import Entity
    from app.models.organization import Organization
    from app.services.export_service import (
        WorkbookMeta,
        build_close_package_workbook,
        build_fs_workbook,
        build_lender_package_workbook,
        build_trial_balance_workbook,
        workbook_to_bytes,
    )
    from app.services.fs_reporting_service import get_fs_statement
    from app.services.reporting_service import get_trial_balance

    params: dict = json.loads(run.parameters_json) if run.parameters_json else {}
    scenario_ids = _get_scenario_ids(run)
    as_of_date_str = params.get("as_of_date")
    as_of_date = (
        datetime.date.fromisoformat(as_of_date_str)
        if as_of_date_str
        else datetime.date.today()
    )

    entity = db.get(Entity, run.entity_id) if run.entity_id else None
    org = db.get(Organization, run.organization_id) if run.organization_id else None
    entity_name = entity.name if entity else ""
    org_name = org.name if org else ""

    meta = WorkbookMeta(
        report_type=run.report_type,
        entity_name=entity_name,
        organization_name=org_name,
        as_of_date=as_of_date,
        generation_time=datetime.datetime.now(datetime.UTC),
    )

    wf_summary = json.loads(run.workflow_summary_json) if run.workflow_summary_json else {}
    tasks = wf_summary.get("tasks", [])
    signoffs = wf_summary.get("signoffs", [])
    issues = wf_summary.get("issues", [])

    val_summary = json.loads(run.validation_summary_json) if run.validation_summary_json else {}
    validation_items: list[dict] = []
    for sev_key in ("errors", "warnings", "info"):
        validation_items.extend(val_summary.get(sev_key, []))

    rtype = run.report_type

    if rtype in ("trial_balance", "comparative_trial_balance",
                 "consolidated_trial_balance"):
        if run.entity_id and scenario_ids:
            tb_rows = get_trial_balance(db, run.entity_id, as_of_date, scenario_ids)
        else:
            tb_rows = []
        wb = build_trial_balance_workbook(
            meta, tb_rows,
            validation_items=validation_items or None,
            workflow_tasks=tasks,
            workflow_signoffs=signoffs,
            issues=issues or None,
        )

    elif rtype in ("balance_sheet", "income_statement",
                   "consolidated_balance_sheet", "consolidated_income_statement"):
        if run.entity_id and scenario_ids:
            tb_rows = get_trial_balance(db, run.entity_id, as_of_date, scenario_ids)
            fs_lines = get_fs_statement(db, run.entity_id, as_of_date, scenario_ids)
        else:
            tb_rows = []
            fs_lines = []
        wb = build_fs_workbook(
            meta, tb_rows, fs_lines,
            validation_items=validation_items or None,
            workflow_tasks=tasks,
            workflow_signoffs=signoffs,
            issues=issues or None,
        )

    elif rtype in ("close_package", "audit_support_package", "qoe_package"):
        if run.entity_id and scenario_ids:
            tb_rows = get_trial_balance(db, run.entity_id, as_of_date, scenario_ids)
            fs_lines = get_fs_statement(db, run.entity_id, as_of_date, scenario_ids)
        else:
            tb_rows = []
            fs_lines = []
        wb = build_close_package_workbook(
            meta, tb_rows, fs_lines,
            validation_items=validation_items or None,
            workflow_tasks=tasks,
            workflow_signoffs=signoffs,
            issues=issues or None,
        )

    elif rtype == "lender_package":
        if run.entity_id and scenario_ids:
            tb_rows = get_trial_balance(db, run.entity_id, as_of_date, scenario_ids)
            fs_lines = get_fs_statement(db, run.entity_id, as_of_date, scenario_ids)
        else:
            tb_rows = []
            fs_lines = []
        wb = build_lender_package_workbook(
            meta, tb_rows, fs_lines,
            validation_items=validation_items or None,
            issues=issues or None,
        )

    else:
        # Fallback: empty TB workbook
        wb = build_trial_balance_workbook(meta, [])

    return workbook_to_bytes(wb, generation_time=meta.generation_time)


