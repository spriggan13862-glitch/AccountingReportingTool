def get_report_run_or_raise(db: Session, run_id: int) -> ReportRun:
    run = db.get(ReportRun, run_id)
    if run is None:
        raise ReportRunNotFoundError(f"ReportRun id={run_id} not found")
    return run


def list_report_runs(
    db: Session,
    organization_id: int,
    report_type: str | None = None,
    status: str | None = None,
    entity_id: int | None = None,
) -> list[ReportRun]:
    q = db.query(ReportRun).filter(ReportRun.organization_id == organization_id)
    if report_type:
        q = q.filter(ReportRun.report_type == report_type)
    if status:
        q = q.filter(ReportRun.status == status)
    if entity_id:
        q = q.filter(ReportRun.entity_id == entity_id)
    return q.order_by(ReportRun.created_at.desc()).all()


def create_report_run(
    db: Session,
    organization_id: int,
    report_type: str,
    output_format: str = "xlsx",
    entity_id: int | None = None,
    accounting_period_id: int | None = None,
    scenario_ids: list[int] | None = None,
    parameters: dict | None = None,
    acting_user: User | None = None,
) -> ReportRun:
    if report_type not in REPORT_TYPES:
        raise ReportValidationError(
            f"Unknown report_type '{report_type}'. "
            f"Valid: {sorted(REPORT_TYPES)}"
        )
    if output_format not in OUTPUT_FORMATS:
        raise ReportValidationError(
            f"Unknown output_format '{output_format}'. Valid: {sorted(OUTPUT_FORMATS)}"
        )

    run = ReportRun(
        organization_id=organization_id,
        created_by_user_id=acting_user.id if acting_user else None,
        report_type=report_type,
        output_format=output_format,
        status="pending",
        entity_id=entity_id,
        accounting_period_id=accounting_period_id,
        scenario_ids_json=json.dumps(scenario_ids) if scenario_ids else None,
        parameters_json=json.dumps(parameters) if parameters else None,
    )
    db.add(run)
    db.flush()
    return run


def execute_report_run(
    db: Session,
    run_id: int,
    storage: StorageBackend,
    org_slug: str,
    acting_user: User | None = None,
) -> ReportRun:
    run = get_report_run_or_raise(db, run_id)

    if run.status in ("running", "completed"):
        raise ReportRunStateError(
            f"ReportRun id={run_id} is already {run.status}. Use rerun to generate again."
        )

    run.status = "running"
    db.flush()

    try:
        wf_summary = _collect_workflow_summary(db, run)
        run.workflow_summary_json = json.dumps(wf_summary)
        db.flush()

        file_bytes = _dispatch_report(db, run)

        ext = ".xlsx" if run.output_format == "xlsx" else f".{run.output_format}"
        file_name = f"{run.report_type}_{uuid.uuid4().hex}{ext}"
        storage_path = f"{org_slug}/reports/{file_name}"
        storage.save(storage_path, file_bytes)

        from app.models.document import Document
        from app.services.storage_service import compute_checksum

        checksum = compute_checksum(file_bytes)
        doc_type = REPORT_TYPE_DOC_TYPE.get(run.report_type, "other")
        doc = Document(
            organization_id=run.organization_id,
            uploaded_by_user_id=run.created_by_user_id,
            file_name=file_name,
            original_file_name=file_name,
            file_extension=ext,
            mime_type=(
                "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
                if run.output_format == "xlsx"
                else "text/plain"
            ),
            file_size_bytes=len(file_bytes),
            storage_path=storage_path,
            document_type=doc_type,
            checksum_sha256=checksum,
        )
        db.add(doc)
        db.flush()

        run.generated_document_id = doc.id
        run.storage_path = storage_path
        run.status = "completed"
        run.completed_at = datetime.datetime.now(datetime.UTC)
        db.flush()

    except Exception:
        run.status = "failed"
        db.flush()
        raise

    return run


def rerun_report(
    db: Session,
    run_id: int,
    storage: StorageBackend,
    org_slug: str,
    acting_user: User | None = None,
) -> ReportRun:
    """Create a new ReportRun from the same parameters and execute it."""
    original = get_report_run_or_raise(db, run_id)

    new_run = create_report_run(
        db,
        organization_id=original.organization_id,
        report_type=original.report_type,
        output_format=original.output_format,
        entity_id=original.entity_id,
        accounting_period_id=original.accounting_period_id,
        scenario_ids=_get_scenario_ids(original) or None,
        parameters=json.loads(original.parameters_json) if original.parameters_json else None,
        acting_user=acting_user,
    )

    return execute_report_run(db, new_run.id, storage, org_slug, acting_user=acting_user)
