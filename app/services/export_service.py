"""
Excel workbook export service.

Produces .xlsx workbooks for all report types using openpyxl.
Sheet builders are composable; package builders assemble multiple sheets.

Deterministic mode: pass deterministic=True (or a fixed generation_time) to
workbook_to_bytes() to get byte-stable output for the same data.
"""

